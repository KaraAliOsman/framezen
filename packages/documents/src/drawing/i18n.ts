export type DrawingMessageKey = MessageKey<Messages>

/** Texto del dibujo en el idioma pedido (español por defecto). */
export function drawingText(key: DrawingMessageKey, params?: MessageParams, locale: Locale = 'es'): string {
  return translate(dictionary, key, params, locale)
}

export const DRAWING_MESSAGES = dictionary

/** Medida «1.200» y «1.200 × 1.500 mm» por idioma; en español, idéntica a la de los documentos. */
export function drawingFormat(locale: Locale = 'es'): { mm: (v: number) => string; size: (w: number, h: number) => string; angle: (deg: number) => string } {
  // Español byte a byte como siempre (títulos accesibles y pruebas e2e los buscan).
  const angle = (deg: number) => `${String(Math.round(deg * 10) / 10).replace('.', locale === 'en' ? '.' : ',')}°`
  if (locale === 'es') return { mm: formatMm, size: formatMeasure, angle }
  const f = createFormatter(locale)
  return {
    mm: (v) => f.mm(Math.round(v * 10) / 10),
    size: (w, h) => f.size(Math.round(w * 10) / 10, Math.round(h * 10) / 10),
    angle,
  }
}
